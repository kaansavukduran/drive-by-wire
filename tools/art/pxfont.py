def text_width(s, gap=1):
    return len(s) * (3 + gap) - gap


def text(img, s, x, y, c, gap=1, shadow=None):
    for i, ch in enumerate(s.upper()):
        g = F3.get(ch, F3["?"])
        for j, row in enumerate(g):
            for k, bit in enumerate(row):
                if bit == "1":
                    if shadow:
                        px.put(img, x + i * (3 + gap) + k + 1, y + j + 1, shadow)
                    px.put(img, x + i * (3 + gap) + k, y + j, c)


