"""Regenerate every Drive-By Wire art asset deterministically.

    python3 tools/art/build.py            # all generators
    python3 tools/art/build.py player     # only some (manifest entries of others are kept)

Writes assets/MANIFEST.json and assets/PROVENANCE.json after EACH generator, so a
partial run still leaves usable metadata. Audits palette/alpha of every PNG it wrote.
"""
import importlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pal  # noqa: E402
import px   # noqa: E402

GENERATORS = [
    ("player", "gen_player"),
    ("enemies", "gen_enemies"),
    ("fx", "gen_fx"),
    ("road", "gen_road"),
    ("momo", "gen_momo"),
    ("garage", "gen_garage"),
    ("characters", "gen_characters"),
    ("ui", "gen_ui"),
    ("fonts", "gen_fonts"),
]

MAN = os.path.join(px.ASSETS, "MANIFEST.json")
PROV = os.path.join(px.ASSETS, "PROVENANCE.json")


def load(path, default):
    if os.path.exists(path):
        with open(path) as f:
            return json.load(f)
    return default


def audit(rel):
    from PIL import Image
    im = Image.open(os.path.join(px.ASSETS, rel)).convert("RGBA")
    bad_c, bad_a = 0, 0
    for c in im.get_flattened_data():
        if c[3] == 0:
            continue
        if c[3] != 255 and rel not in px.GLOW_OK:
            bad_a += 1
        if c[:3] not in pal.ALL_RGB:
            bad_c += 1
    return bad_c, bad_a


def main(only):
    man = load(MAN, {})
    prov = load(PROV, {})
    man.setdefault("sheets", {})
    man.setdefault("images", {})
    prov.setdefault("files", {})
    for key, mod in GENERATORS:
        if only and key not in only:
            continue
        try:
            m = importlib.import_module(mod)
        except ModuleNotFoundError as e:
            if e.name == mod:
                print("skip (not written yet):", mod)
                continue
            raise
        px.MANIFEST["sheets"].clear()
        px.MANIFEST["images"].clear()
        px.MANIFEST.pop("extra", None)
        px.PROVENANCE["files"].clear()
        m.build()
        man["sheets"].update(px.MANIFEST["sheets"])
        man["images"].update(px.MANIFEST["images"])
        for k, v in px.MANIFEST.get("extra", {}).items():
            man[k] = v
        prov["files"].update(px.PROVENANCE["files"])
        for path in list(px.PROVENANCE["files"]):
            rel = path[len("assets/"):]
            if rel.endswith(".png"):
                bc, ba = audit(rel)
                if bc or ba:
                    print(f"  AUDIT {rel}: {bc} off-palette, {ba} partial-alpha px")
            prov["files"][path]["sha256"] = px.sha256(os.path.join(px.ROOT, path))
        man.update({
            "version": "0.1.0",
            "generator": "tools/art/build.py",
            "logical_resolution": [640, 360],
            "texture_filter": "nearest",
            "palette": {"path": "assets/palette.png", "colors": len(pal.ALL),
                        "gpl": "assets/palette.gpl"},
            "conventions": "Frame index n is at column n % columns, row n // columns. "
                           "anchor = pivot in frame pixels (place node position here). "
                           "collision = suggested rect in frame pixels. Vehicles face up. "
                           "Animations repeat indices to make holds.",
        })
        prov.update({
            "generator": "tools/art/build.py",
            "note": "All PNGs are regenerated byte-identically by the scripts in tools/art. "
                    "Procedural art uses only the 64-colour palette in tools/art/pal.py.",
        })
        with open(MAN, "w") as f:
            json.dump(man, f, indent=1, ensure_ascii=False, sort_keys=True)
        with open(PROV, "w") as f:
            json.dump(prov, f, indent=1, ensure_ascii=False, sort_keys=True)
        print("ok", key, "->", ", ".join(sorted(px.MANIFEST["sheets"]) + sorted(px.MANIFEST["images"])))
    write_palette()


def write_palette():
    img = px.new(len(pal.ALL), 1)
    for i, c in enumerate(pal.ALL):
        img.putpixel((i, 0), c)
    img.save(os.path.join(px.ASSETS, "palette.png"))
    with open(os.path.join(px.ASSETS, "palette.gpl"), "w") as f:
        f.write("GIMP Palette\nName: Drive-By Wire\nColumns: 8\n#\n")
        for name, c in pal.P.items():
            f.write(f"{c[0]:3d} {c[1]:3d} {c[2]:3d}\t{name}\n")


if __name__ == "__main__":
    main(set(sys.argv[1:]))
